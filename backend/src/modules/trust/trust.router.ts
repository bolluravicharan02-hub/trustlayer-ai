import { Router, Request, Response, NextFunction } from 'express';
import { requireAuth } from '../../middleware/auth.middleware.js';
import { requireOrgMember } from '../../middleware/authorization.middleware.js';
import { withTenantTransaction } from '../../database/tenant-transaction.js';
import { isGrokConfigured } from '../../config/grok.js';
import { env } from '../../config/env.js';
import { SYSTEM_PROMPT } from '../../services/ai-investigation.service.js';

export const trustRouter = Router();

// Trust Overview
trustRouter.get(
  '/trust/overview',
  requireAuth,
  requireOrgMember('viewer'),
  async (req: Request, res: Response, next: NextFunction): Promise<void> => {
    try {
      const stats = await withTenantTransaction(
        { organizationId: req.organization!.id, userId: req.user!.id, role: req.organization!.role },
        async (client) => {
          const runsRes = await client.query(
            `SELECT COUNT(*) as total,
                    AVG(latency_ms) as "avgLatency",
                    COUNT(*) FILTER (WHERE status = 'completed') as completed,
                    COUNT(*) FILTER (WHERE status = 'failed') as failed
             FROM ai_analysis_runs
             WHERE organization_id = $1`,
            [req.organization!.id]
          );

          return {
            totalRuns: parseInt(runsRes.rows[0].total, 10),
            completedRuns: parseInt(runsRes.rows[0].completed, 10),
            failedRuns: parseInt(runsRes.rows[0].failed, 10),
            avgLatencyMs: Math.round(parseFloat(runsRes.rows[0].avgLatency || '0')),
          };
        }
      );

      res.json({
        success: true,
        data: {
          model: {
            configuredName: env.GROK_MODEL,
            provider: 'xAI (Grok)',
            isLiveConnected: isGrokConfigured(),
            runtimeMode: isGrokConfigured() ? 'live_api' : 'local_rule_advisory',
            maxOutputTokens: env.GROK_MAX_OUTPUT_TOKENS,
            timeoutMs: env.GROK_TIMEOUT_MS,
          },
          governance: {
            humanInTheLoop: true,
            prohibitedConsequentialActions: [
              'Automatic account locking',
              'Silent data deletion',
              'Unapproved credential invalidation',
              'Firewall policy modification without authorization',
            ],
            dataSanitizationGuarantees: [
              'All API keys and credentials redacted prior to model transit',
              'Payment card numbers validated via Luhn and masked',
              'Zero unredacted storage of user raw upload streams',
              'Append-only cryptographic audit logging of all AI queries',
            ],
            distinction: {
              deterministic: 'Generated by strictly coded, mathematical security rules and deterministic scoring (0-100)',
              probabilistic: 'Generated by xAI Grok reasoning as advisory hypotheses and context synthesis',
            },
          },
          telemetry: stats,
        },
      });
    } catch (err) {
      next(err);
    }
  }
);

// AI Analysis History
trustRouter.get(
  '/trust/ai-runs',
  requireAuth,
  requireOrgMember('viewer'),
  async (req: Request, res: Response, next: NextFunction): Promise<void> => {
    try {
      const runs = await withTenantTransaction(
        { organizationId: req.organization!.id, userId: req.user!.id, role: req.organization!.role },
        async (client) => {
          const res = await client.query(
            `SELECT r.id, r.alert_id as "alertId", r.model_name as "modelName",
                    r.analysis_type as "analysisType", r.prompt_version as "promptVersion",
                    r.input_digest as "inputDigest", r.status, r.latency_ms as "latencyMs",
                    r.created_at as "createdAt", r.completed_at as "completedAt",
                    u.full_name as "requestedByName", a.title as "alertTitle"
             FROM ai_analysis_runs r
             JOIN users u ON u.id = r.requested_by
             LEFT JOIN security_alerts a ON a.id = r.alert_id
             WHERE r.organization_id = $1
             ORDER BY r.created_at DESC
             LIMIT 50`,
            [req.organization!.id]
          );
          return res.rows;
        }
      );

      res.json({
        success: true,
        data: runs,
      });
    } catch (err) {
      next(err);
    }
  }
);

// AI Analysis Details
trustRouter.get(
  '/trust/ai-runs/:id',
  requireAuth,
  requireOrgMember('viewer'),
  async (req: Request, res: Response, next: NextFunction): Promise<void> => {
    try {
      const run = await withTenantTransaction(
        { organizationId: req.organization!.id, userId: req.user!.id, role: req.organization!.role },
        async (client) => {
          const res = await client.query(
            `SELECT r.id, r.alert_id as "alertId", r.model_name as "modelName",
                    r.analysis_type as "analysisType", r.prompt_version as "promptVersion",
                    r.input_digest as "inputDigest", r.output, r.status, r.error_code as "errorCode",
                    r.latency_ms as "latencyMs", r.created_at as "createdAt", r.completed_at as "completedAt",
                    u.full_name as "requestedByName", a.title as "alertTitle"
             FROM ai_analysis_runs r
             JOIN users u ON u.id = r.requested_by
             LEFT JOIN security_alerts a ON a.id = r.alert_id
             WHERE r.id = $1 AND r.organization_id = $2`,
            [req.params.id, req.organization!.id]
          );
          return res.rows[0] || null;
        }
      );

      if (!run) {
        res.status(404).json({ success: false, error: { code: 'NOT_FOUND', message: 'AI run not found' } });
        return;
      }

      res.json({
        success: true,
        data: run,
      });
    } catch (err) {
      next(err);
    }
  }
);

